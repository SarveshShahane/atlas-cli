@app.post("/product/projects", tags=["Atlas product"])
async def create_product_project(
    file: UploadFile = File(...),
    name: str = Form("Untitled project"),
    goal: str = Form(""),
    target: str = Form(""),
):
    suffix = Path(file.filename or "").suffix.lower()
    if suffix not in ALLOWED_UPLOAD_SUFFIXES:
        raise HTTPException(status_code=400, detail="Choose a CSV, JSON, or Parquet data file.")
    project_id = uuid.uuid4().hex[:10]
    project_upload_dir = UPLOAD_DIR / project_id
    project_upload_dir.mkdir(parents=True, exist_ok=True)
    safe_name = Path(file.filename or "dataset").name
    destination = project_upload_dir / safe_name
    with destination.open("wb") as target_file:
        shutil.copyfileobj(file.file, target_file)
    timestamp = datetime.now(timezone.utc).isoformat()
    project = {
        "id": project_id,
        "name": name.strip() or "Untitled project",
        "dataset_name": safe_name,
        "dataset_path": str(destination.relative_to(PROJECT_DIR)).replace("\\", "/"),
        "goal": goal.strip(),
        "target": target.strip(),
        "run_id": project_id,
        "created_at": timestamp,
        "updated_at": timestamp,
    }
    projects = _load_projects()
    projects.append(project)
    _save_projects(projects)
    try:
        from atlas_cli.db.session import create_db_and_tables
        create_db_and_tables()
    except Exception:
        logger.warning("Could not initialize optional Atlas database for product project.", exc_info=True)
    
    # Automatically analyze uploaded dataset so stage 1 data health is populated immediately
    try:
        analyze_args = [str(destination), "--run-id", project_id]
        if target.strip():
            analyze_args += ["--target", target.strip()]
        await _run_atlas_command("analyze", analyze_args)
    except Exception as exc:
        logger.warning(f"Initial analyze profiling warning for project {project_id}: {exc}")

    return _product_snapshot(project)


